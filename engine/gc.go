// gcSpans holds the expiry spans of one GC pass: "entity.expire" when the
// entity is removed (reason "hard" or "lifetime"), "entity.expire.components"
// when only some components lapse. Expiry continues the trace of the entity's
// current version (derived from id and fresh), so it shows up under the
// change that produced that version; an entity without a version gets no
// span. The returned ctx carries the span for the bus notification, so
// watchers' send spans hang off it.
type gcSpans map[string]entityWrite

func (g gcSpans) expire(id string, es *entityState, name, reason string) context.Context {
	attrs := []attribute.KeyValue{tracing.AttrEntityID.String(id)}
	if reason != "" {
		attrs = append(attrs, attribute.String("hydris.expire.reason", reason))
	}
	ctx, span := tracing.ContinueSpan(context.Background(), es.version(), name, trace.WithAttributes(attrs...))
	if !span.IsRecording() {
		return ctx
	}
	g[id] = entityWrite{ctx: ctx, span: span}
	return ctx
}

func (g gcSpans) ctx(id string) context.Context {
	if w, ok := g[id]; ok {
		return w.ctx
	}
	return context.Background()
}

func (g gcSpans) end() {
	for _, w := range g {
		w.span.End()
	}
}

func (s *WorldServer) GC() {
	now := time.Now()

	s.l.Lock()
	spans := gcSpans{}
	defer spans.end()
	var changed []string
	var expired []string
	// A lapsed lifetime is a time event, not a push, so an anchor that ages out
	// here would otherwise linger in the cached pool until some unrelated write.
	// Record when one is removed so we rebuild the trust set before unlocking.
	anchorChanged := false

	// Phase 0: Hard-expire entities marked by ExpireEntity.
	// These are removed unconditionally regardless of component lifetimes.
	for entityID, es := range s.head {
		if !es.hardExpire {
			continue
		}
		anchorChanged = anchorChanged || isTrustAnchorLocked(es)
		s.expireEntity(spans.expire(entityID, es, "entity.expire", "hard"), entityID, es)
		expired = append(expired, entityID)
	}

	// Phase 1: Per-component expiry for entities with lifetimes.
	for entityID, es := range s.head {
		if len(es.lifetimes) == 0 {
			continue
		}

		// Count how many tracked (has lifetime) components expire this tick.
		// Components without a lifetime or generated by transformers don't
		// count toward keeping the entity alive and are cleaned up together
		// with the tracked ones.
		//
		// A manual control frame is a command with a lifetime of a fraction of
		// a second. It lapses by itself, and never takes the entity with it.
		var expiringFields []int32
		var dependentFields []int32
		tracked, trackedExpiring := 0, 0
		for protoNum, cm := range es.lifetimes {
			if cm.NoLifetime || cm.Generated {
				dependentFields = append(dependentFields, protoNum)
				continue
			}
			lapsed := !cm.Until.IsZero() && now.After(cm.Until)
			if protoNum == manualFrameProtoNum {
				if lapsed {
					expiringFields = append(expiringFields, protoNum)
				}
				continue
			}
			tracked++
			if lapsed {
				trackedExpiring++
				expiringFields = append(expiringFields, protoNum)
			}
		}
		if len(expiringFields) == 0 {
			continue
		}

		allExpiring := tracked > 0 && trackedExpiring >= tracked
		if allExpiring {
			expiringFields = append(expiringFields, dependentFields...)
		}

		anchorChanged = anchorChanged || isTrustAnchorLocked(es)
		if allExpiring {
			s.expireEntity(spans.expire(entityID, es, "entity.expire", "lifetime"), entityID, es)
			expired = append(expired, entityID)
		} else {
			// Clone so we don't mutate the pointer already shared with the bus.
			updated := goproto.Clone(es.entity).(*proto.Entity)
			ectx := spans.expire(entityID, es, "entity.expire.components", "")
			v := reflect.ValueOf(updated).Elem()
			for _, protoNum := range expiringFields {
				if fieldIdx, ok := protoNumToFieldIdx[protoNum]; ok {
					f := v.Field(fieldIdx)
					if f.Kind() == reflect.Pointer && f.CanSet() {
						f.Set(reflect.Zero(f.Type()))
					}
				}
				delete(es.lifetimes, protoNum)
			}
			es.entity = updated
			s.headView[entityID] = updated
			changed = append(changed, entityID)
			s.bus.Dirty(ectx, entityID, updated, proto.EntityChange_EntityChangeUpdated)
		}
	}

	// Phase 2: Fallback entity-level expiry for entities without lifetimes
	// (e.g., transformer-generated entities that bypass Push).
	for k, es := range s.head {
		if len(es.lifetimes) > 0 {
			continue
		}
		e := es.entity
		if e.Lifetime != nil && e.Lifetime.Until.IsValid() && now.After(e.Lifetime.Until.AsTime()) {
			anchorChanged = anchorChanged || isTrustAnchorLocked(es)
			s.expireEntity(spans.expire(k, es, "entity.expire", "lifetime"), k, es)
			expired = append(expired, k)
		}
	}

	for _, id := range expired {
		if s.isRemoteEntity(id) {
			continue
		}
		var lts map[int32]meta.Component
		if es, ok := s.head[id]; ok {
			lts = es.lifetimes
		}
		upserted, removed, genBy := transform.RunTransformers(spans.ctx(id), s.transformers, s.headView, s.bus, id, lts)
		s.syncTransformerResults(upserted, removed)
		s.markGeneratedComponents(id, genBy[id])
		for _, uid := range upserted {
			s.markGeneratedComponents(uid, genBy[uid])
		}
	}
	for _, id := range changed {
		if s.isRemoteEntity(id) {
			continue
		}
		var lts map[int32]meta.Component
		if es, ok := s.head[id]; ok {
			lts = es.lifetimes
		}
		upserted, removed, genBy := transform.RunTransformers(spans.ctx(id), s.transformers, s.headView, s.bus, id, lts)
		s.syncTransformerResults(upserted, removed)
		s.markGeneratedComponents(id, genBy[id])
		for _, uid := range upserted {
			s.markGeneratedComponents(uid, genBy[uid])
		}
	}

	// An anchor aged out of the trust set: recompile so verifyMTLS stops
	// honouring certificates it issued, rather than waiting for the next write.
	if anchorChanged && s.policyEval != nil {
		go s.policyEval.Rebuild()
	}
	s.l.Unlock()
}

// deleteArtifactBlob deletes the blob for an artifact entity from storage.
func deleteArtifactBlob(entity *proto.Entity) {
	if entity.Artifact == nil || entity.Artifact.Id == "" { //nolint:staticcheck // SA1019: Artifact.Id migration pending
		return
	}
	if artifacts.Server == nil {
		return
	}
	if err := artifacts.Server.DeleteBlob(entity.Artifact.Id); err != nil { //nolint:staticcheck // SA1019: Artifact.Id migration pending
		slog.Warn("failed to delete artifact blob on expiry", "id", entity.Artifact.Id, "error", err) //nolint:staticcheck // SA1019: Artifact.Id migration pending
	}
}
